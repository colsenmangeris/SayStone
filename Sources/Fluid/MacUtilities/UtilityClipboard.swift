import AppKit
import Foundation

/// The caller supplies target validation and event delivery; this type only owns clipboard data.
@MainActor
enum UtilityClipboard {
    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autogeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    static let restoredType = NSPasteboard.PasteboardType("org.nspasteboard.RestoredType")
    private static let maximumSnapshotBytes = 33_554_432
    private static var busyPasteboards = Set<NSPasteboard.Name>()

    @discardableResult
    static func copy(_ text: String, to pasteboard: NSPasteboard = .general) throws -> Bool {
        try UtilityActionRegistry.validate(.init(id: .copyText, text: text))
        guard !busyPasteboards.contains(pasteboard.name) else { throw UtilityActionError.clipboardBusy }
        pasteboard.clearContents()
        guard pasteboard.setString(text, forType: .string) else {
            throw UtilityActionError.clipboardUnavailable
        }
        return true
    }

    /// Preserves every materialized format, and restores only while the change count is ours.
    /// A matching string is insufficient: another actor may have copied identical text.
    static func withTemporaryText(
        _ text: String,
        on pasteboard: NSPasteboard = .general,
        restoreDelay: TimeInterval = 0.15,
        targetIsValid: @escaping @MainActor () -> Bool,
        paste: @escaping @MainActor () -> Bool
    ) async throws {
        try UtilityActionRegistry.validate(.init(id: .pasteText, text: text))
        try Task.checkCancellation()
        guard targetIsValid() else { throw UtilityActionError.targetChanged }
        guard busyPasteboards.insert(pasteboard.name).inserted else {
            throw UtilityActionError.clipboardBusy
        }
        defer { busyPasteboards.remove(pasteboard.name) }

        let originalChangeCount = pasteboard.changeCount
        let snapshot = try capture(pasteboard)
        guard pasteboard.changeCount == originalChangeCount else {
            throw UtilityActionError.clipboardUnavailable
        }
        try Task.checkCancellation()
        guard targetIsValid() else { throw UtilityActionError.targetChanged }
        guard pasteboard.changeCount == originalChangeCount else {
            throw UtilityActionError.clipboardUnavailable
        }

        let temporaryItem = NSPasteboardItem()
        temporaryItem.setString(text, forType: .string)
        temporaryItem.setData(Data(), forType: transientType)
        temporaryItem.setData(Data(), forType: autogeneratedType)
        pasteboard.clearContents()
        let written = pasteboard.writeObjects([temporaryItem])
        let ownedChangeCount = pasteboard.changeCount
        defer {
            if pasteboard.changeCount == ownedChangeCount {
                restore(snapshot, to: pasteboard)
            }
        }
        guard written else { throw UtilityActionError.clipboardUnavailable }
        try Task.checkCancellation()
        guard targetIsValid() else { throw UtilityActionError.targetChanged }
        guard paste() else { throw UtilityActionError.clipboardUnavailable }

        // AppKit event delivery needs a short interval for the receiving application to consume it.
        let boundedDelay = restoreDelay.isFinite ? max(0, min(restoreDelay, 1)) : 0.15
        if boundedDelay > 0 {
            try await Task.sleep(nanoseconds: UInt64(boundedDelay * 1_000_000_000))
        }
        try Task.checkCancellation()
    }

    private struct ItemSnapshot {
        var formats: [NSPasteboard.PasteboardType: Data]
    }

    private static func capture(_ pasteboard: NSPasteboard) throws -> [ItemSnapshot] {
        var totalBytes = 0
        return try (pasteboard.pasteboardItems ?? []).map { item in
            var formats = [NSPasteboard.PasteboardType: Data]()
            for type in item.types {
                // AppKit also advertises synthesized formats that cannot materialize data.
                // Preserve every supported format rather than failing on these aliases.
                guard let data = item.data(forType: type) else { continue }
                guard data.count <= maximumSnapshotBytes - totalBytes else {
                    throw UtilityActionError.clipboardTooLarge
                }
                totalBytes += data.count
                formats[type] = data
            }
            guard !formats.isEmpty else { throw UtilityActionError.clipboardUnavailable }
            return ItemSnapshot(formats: formats)
        }
    }

    private static func restore(_ snapshot: [ItemSnapshot], to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        let items = snapshot.map { saved in
            let item = NSPasteboardItem()
            for (type, data) in saved.formats {
                item.setData(data, forType: type)
            }
            // Restoration is not a fresh copy from the now-frontmost app. Prevent
            // clipboard collection from reclassifying previously excluded text.
            if saved.formats[restoredType] == nil {
                item.setData(Data(), forType: restoredType)
            }
            return item
        }
        if !items.isEmpty { _ = pasteboard.writeObjects(items) }
    }
}
