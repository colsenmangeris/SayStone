import AppKit
import Darwin
import Foundation

@main
struct UtilityCoreTests {
    enum Failure: Error { case check(String) }

    @MainActor
    static func main() async throws {
        guard CommandLine.arguments.count == 2 else { throw Failure.check("Pass the synthetic fixture executable.") }
        try registryTests()
        try await clipboardTests()
        try await processTests(executable: URL(fileURLWithPath: CommandLine.arguments[1]))
        print("Utility core fixtures passed: typed actions, pasteboard preservation/focus/cancellation, bounded process output/timeouts/cancellation.")
    }

    static func check(_ condition: @autoclosure () throws -> Bool, _ message: String) throws {
        if try !condition() { throw Failure.check(message) }
    }

    static func rejects(_ request: UtilityActionRequest) throws {
        do {
            try UtilityActionRegistry.validate(request)
            throw Failure.check("Expected request rejection: \(request.id)")
        } catch is UtilityActionError { }
    }

    static func registryTests() throws {
        try check(Set(UtilityActionRegistry.descriptors.map(\.id)) == Set(UtilityActionID.allCases), "Missing action descriptor")
        try check(UtilityActionRegistry.descriptors.count == UtilityActionID.allCases.count, "Duplicate action descriptor")
        let fixtureText = "  Model v2\n total 17.5  "
        let request = UtilityActionRequest(id: .transformText, text: fixtureText, transform: .collapseWhitespace)
        try check(try JSONDecoder().decode(UtilityActionRequest.self, from: JSONEncoder().encode(request)) == request, "Request round trip")
        try check(UtilityTextTransform.collapseWhitespace.apply(to: fixtureText) == "Model v2 total 17.5", "Whitespace transformation")
        try check(UtilityTextTransform.removeLineBreaks.apply(to: "A\r\nB\nC") == "A B C", "Line break transformation")
        try check(UtilityTextTransform.trim.apply(to: "  identifier-42  ") == "identifier-42", "Trim transformation")
        try check(UtilityTextTransform.uppercase.apply(to: "Case-17") == "CASE-17", "Uppercase transformation")
        try check(UtilityTextTransform.lowercase.apply(to: "Case-17") == "case-17", "Lowercase transformation")
        try rejects(.init(id: .copyText))
        try rejects(.init(id: .pasteText, text: ""))
        try rejects(.init(id: .transformText, text: "fixture"))
        try rejects(.init(id: .insertSnippet))
        try rejects(.init(id: .copyText, text: String(repeating: "x", count: UtilityActionRegistry.maximumTextBytes + 1)))
        for url in ["file:///tmp/fixture", "javascript:alert(1)", "https://", "https://example.com/invalid space"] {
            try rejects(.init(id: .openURL, urlString: url))
        }
        try UtilityActionRegistry.validate(.init(id: .openURL, urlString: "https://example.com/path?q=fixture"))
        try UtilityActionRegistry.validate(.init(id: .openURL, urlString: "mailto:fixture@example.com"))
        try rejects(.init(id: .launchApp, bundleIdentifier: "invalid app"))
        try UtilityActionRegistry.validate(.init(id: .launchApp, bundleIdentifier: "com.apple.TextEdit"))
        try rejects(.init(id: .runAppleShortcut, shortcutName: "--help"))
        try rejects(.init(id: .runAppleShortcut, shortcutName: "Fixture\nname"))
        try UtilityActionRegistry.validate(.init(id: .runAppleShortcut, shortcutName: "Fixture; $(nothing) 'quotes'"))
    }

    @MainActor
    static func clipboardTests() async throws {
        // Every clipboard read below uses our named fixture board, never NSPasteboard.general.
        let board = NSPasteboard(name: .init("com.architech.saystone.utility-core-tests.\(UUID().uuidString)"))
        defer { board.releaseGlobally() }
        let custom = NSPasteboard.PasteboardType("com.architech.fixture-format")
        let originalRTF = Data([0, 1, 2, 3, 255])
        func seed() {
            let first = NSPasteboardItem()
            first.setString("authored original", forType: .string)
            first.setData(originalRTF, forType: .rtf)
            first.setData(Data([42, 43]), forType: custom)
            let second = NSPasteboardItem()
            second.setString("second item", forType: .string)
            board.clearContents()
            _ = board.writeObjects([first, second])
        }
        seed()
        var pasted = false
        try await UtilityClipboard.withTemporaryText("authored temporary", on: board, restoreDelay: 0, targetIsValid: { true }) {
            pasted = board.string(forType: .string) == "authored temporary"
                && board.types?.contains(UtilityClipboard.transientType) == true
                && board.types?.contains(UtilityClipboard.autogeneratedType) == true
            return true
        }
        try check(pasted, "Temporary clipboard markers missing")
        try check(board.pasteboardItems?.count == 2, "Multiple clipboard items not restored")
        try check(board.data(forType: .rtf) == originalRTF, "RTF bytes not restored")
        try check(board.data(forType: custom) == Data([42, 43]), "Custom format not restored")
        try check(board.string(forType: .string) == "authored original\nsecond item", "Original text not restored")
        try check(board.pasteboardItems?.allSatisfy { $0.types.contains(UtilityClipboard.restoredType) } == true, "Restoration marker missing from clipboard items")

        seed()
        try await UtilityClipboard.withTemporaryText("identical copy", on: board, restoreDelay: 0, targetIsValid: { true }) {
            // An independent copy of identical text must retain its new payload.
            board.clearContents()
            board.setString("identical copy", forType: .string)
            board.setString("authored new formatting", forType: .html)
            return true
        }
        try check(board.string(forType: .string) == "identical copy", "Concurrent identical copy overwritten")
        try check(board.string(forType: .html) == "authored new formatting", "Concurrent format overwritten")
        try check(board.types?.contains(UtilityClipboard.restoredType) != true, "Independent copy incorrectly marked as restored")

        seed()
        let initialCount = board.changeCount
        do {
            try await UtilityClipboard.withTemporaryText("fixture", on: board, targetIsValid: { false }, paste: { true })
            throw Failure.check("Invalid focus accepted")
        } catch UtilityActionError.targetChanged { }
        try check(board.changeCount == initialCount, "Invalid target changed clipboard")

        var snapshotTargetChecks = 0
        do {
            try await UtilityClipboard.withTemporaryText(
                "fixture",
                on: board,
                restoreDelay: 0,
                targetIsValid: {
                    snapshotTargetChecks += 1
                    if snapshotTargetChecks == 2 {
                        board.clearContents()
                        board.setString("copy during focus validation", forType: .string)
                    }
                    return true
                },
                paste: { true }
            )
            throw Failure.check("Changed clipboard snapshot accepted")
        } catch UtilityActionError.clipboardUnavailable { }
        try check(board.string(forType: .string) == "copy during focus validation", "Copy before temporary write overwritten")

        seed()
        var targetChecks = 0
        var dispatches = 0
        do {
            try await UtilityClipboard.withTemporaryText(
                "fixture",
                on: board,
                restoreDelay: 0,
                targetIsValid: {
                    targetChecks += 1
                    return targetChecks < 3
                },
                paste: {
                    dispatches += 1
                    return true
                }
            )
            throw Failure.check("Late focus change accepted")
        } catch UtilityActionError.targetChanged { }
        try check(dispatches == 0, "Pasted after late focus change")
        try check(board.string(forType: .string) == "authored original\nsecond item", "Late focus failure not restored")

        do {
            try await UtilityClipboard.withTemporaryText("fixture", on: board, restoreDelay: 0, targetIsValid: { true }, paste: { false })
            throw Failure.check("Failed delivery accepted")
        } catch UtilityActionError.clipboardUnavailable { }
        try check(board.string(forType: .string) == "authored original\nsecond item", "Failed paste not restored")

        var cancellationPasteReached = false
        var overlappingCopyRejected = false
        let task = Task { @MainActor in
            try await UtilityClipboard.withTemporaryText("cancellation fixture", on: board, restoreDelay: 1, targetIsValid: { true }) {
                cancellationPasteReached = true
                do { try UtilityClipboard.copy("overlap", to: board) } catch UtilityActionError.clipboardBusy {
                    overlappingCopyRejected = true
                } catch { }
                return true
            }
        }
        try await Task.sleep(nanoseconds: 40_000_000)
        task.cancel()
        do {
            try await task.value
            throw Failure.check("Clipboard cancellation ignored")
        } catch is CancellationError { }
        try check(cancellationPasteReached && overlappingCopyRejected, "Overlapping transaction guard missing")
        try check(board.string(forType: .string) == "authored original\nsecond item", "Cancellation did not restore clipboard")
        try UtilityClipboard.copy("authored copy", to: board)
        try check(board.string(forType: .string) == "authored copy", "Copy action failed")
    }

    @MainActor
    static func processTests(executable: URL) async throws {
        let authoredArguments = ["a b", "literal; $(touch nothing)", "quote'\"", "--flag-as-data"]
        let arguments = try await UtilityProcessRunner.run(executableURL: executable, arguments: ["arguments"] + authoredArguments)
        try check(arguments.succeeded, "Arguments fixture failed")
        try check(try JSONDecoder().decode([String].self, from: Data(arguments.stdout.utf8)) == authoredArguments, "Arguments were interpreted or changed")
        // Exercise the completion race with several immediately exiting children at once.
        let immediateResults = try await withThrowingTaskGroup(of: Bool.self) { group in
            for _ in 0..<12 {
                group.addTask {
                    try await UtilityProcessRunner.run(executableURL: executable, arguments: ["arguments", "fast exit"], timeout: 3).succeeded
                }
            }
            var results = [Bool]()
            for try await result in group { results.append(result) }
            return results
        }
        try check(immediateResults.count == 12 && immediateResults.allSatisfy { $0 }, "Immediate process completion was lost")
        let flood = try await UtilityProcessRunner.run(executableURL: executable, arguments: ["flood"], timeout: 5, maxOutputBytes: 4_096)
        try check(flood.succeeded && flood.outputTruncated, "Flood did not complete with bounded output")
        try check(flood.stdout.utf8.count == 4_096 && flood.stderr.utf8.count == 4_096, "Output cap failed")
        let nonzero = try await UtilityProcessRunner.run(executableURL: executable, arguments: ["exit"])
        try check(nonzero.exitCode == 7 && nonzero.stdout == "authored stdout" && nonzero.stderr == "authored stderr", "Nonzero exit result lost")

        let timeoutStarted = ProcessInfo.processInfo.systemUptime
        var mainActorResponsive = false
        let pulse = Task { @MainActor in
            try await Task.sleep(nanoseconds: 50_000_000)
            mainActorResponsive = true
        }
        do {
            _ = try await UtilityProcessRunner.run(executableURL: executable, arguments: ["sleep"], timeout: 0.15)
            throw Failure.check("Process timeout ignored")
        } catch UtilityProcessError.timedOut { }
        try await pulse.value
        try check(mainActorResponsive && ProcessInfo.processInfo.systemUptime - timeoutStarted < 1.5, "Timeout blocked UI or was not bounded")

        let cancelled = Task {
            try await UtilityProcessRunner.run(executableURL: executable, arguments: ["sleep"], timeout: 10)
        }
        try await Task.sleep(nanoseconds: 60_000_000)
        let cancelStarted = ProcessInfo.processInfo.systemUptime
        cancelled.cancel()
        do {
            _ = try await cancelled.value
            throw Failure.check("Process cancellation ignored")
        } catch is CancellationError { }
        try check(ProcessInfo.processInfo.systemUptime - cancelStarted < 1.5, "Cancellation was not bounded")

        let folder = FileManager.default.temporaryDirectory.appendingPathComponent("UtilityCore-\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: folder) }
        let childFile = folder.appendingPathComponent("synthetic-child-pid")
        do {
            _ = try await UtilityProcessRunner.run(executableURL: executable, arguments: ["tree", childFile.path], timeout: 0.2)
            throw Failure.check("Tree timeout ignored")
        } catch UtilityProcessError.timedOut { }
        let childPID = try String(contentsOf: childFile, encoding: .utf8).trimmingCharacters(in: .whitespacesAndNewlines)
        guard let pid = Int32(childPID) else { throw Failure.check("Missing synthetic child identity") }
        try await Task.sleep(nanoseconds: 350_000_000)
        var info = proc_bsdinfo()
        let size = Int32(MemoryLayout<proc_bsdinfo>.size)
        let status = proc_pidinfo(pid, PROC_PIDTBSDINFO, 0, &info, size)
        try check(status != size || info.pbi_status == SZOMB, "Owned descendant survived timeout")

        do {
            _ = try await UtilityProcessRunner.run(executableURL: folder.appendingPathComponent("missing"))
            throw Failure.check("Missing executable accepted")
        } catch UtilityProcessError.launchFailed { }
        do {
            _ = try await UtilityProcessRunner.run(executableURL: executable, timeout: .infinity)
            throw Failure.check("Invalid timeout accepted")
        } catch UtilityProcessError.invalidConfiguration { }
    }
}
